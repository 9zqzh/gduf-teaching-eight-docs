# ---------------------------------------------------------------- copying
def copy_teacher_profile(source, out_dir, teacher_name):
    if not source or not os.path.exists(source):
        return None
    ext = os.path.splitext(source)[1].lower() or ".docx"
    target = os.path.join(out_dir, f"2、教师简历（{teacher_name or '教师'}）{ext}")
    if os.path.abspath(source) != os.path.abspath(target):
        shutil.copy2(source, target)
    return target


def copy_courseware(source, out_dir):
    if not source or not os.path.exists(source):
        return None
    target = os.path.join(out_dir, "6、教学课件")
    if os.path.abspath(source) == os.path.abspath(target):
        return target
    if os.path.isdir(source):
        shutil.copytree(source, target, dirs_exist_ok=True)
    else:
        os.makedirs(target, exist_ok=True)
        shutil.copy2(source, os.path.join(target, os.path.basename(source)))
    return target


# ---------------------------------------------------------------- main
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--docs", default="", help="comma separated, e.g. 1,3,4,5,7,8,2")
    parser.add_argument("--teacher-profile", default="")
    parser.add_argument("--courseware", default="")
    parser.add_argument("--no-copy", action="store_true", help="do not copy documents 2 and 6")
    args = parser.parse_args()

    with open(args.data, "r", encoding="utf-8") as f:
        data = json.load(f)
    meta = data.get("meta") or {}
    course = data.get("course") or {}
    teacher = data.get("teacher") or {}
    options = data.get("options") or {}

    docs = [int(x) for x in args.docs.split(",") if x.strip()] if args.docs else options.get("docs") or [1, 3, 4, 5]
    os.makedirs(args.out, exist_ok=True)

    builders = {1: build_doc1, 3: build_doc3, 4: build_doc4, 5: build_doc5, 7: build_doc7, 8: build_doc8}
    generated = []
    for doc_no in docs:
        if doc_no == 2:
            generated.append(build_doc2(teacher, meta, args.out))
        elif doc_no == 6:
            continue
        elif doc_no in builders:
            generated.append(builders[doc_no](course, meta, args.out))
        else:
            print(f"skip unknown document number: {doc_no}")

    copied = []
    teacher_source = args.teacher_profile or meta.get("teacher_profile")
    if not args.no_copy and teacher_source:
        result = copy_teacher_profile(teacher_source, args.out, teacher.get("name") or meta.get("teacher_name"))
        if result:
            copied.append(result)
    courseware_source = args.courseware or meta.get("courseware")
    if not args.no_copy and courseware_source:
        result = copy_courseware(courseware_source, args.out)
        if result:
            copied.append(result)

    manifest = {
        "course": course.get("name", ""),
        "generated": [os.path.basename(p) for p in generated],
        "copied": [os.path.basename(p) for p in copied],
        "missing_or_placeholder": MISSING,
        "courseware_source": courseware_source or "",
        "teacher_profile_source": teacher_source or "",
    }
    with open(os.path.join(args.out, "生成记录.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)

    print("generated:", ", ".join(os.path.basename(p) for p in generated) or "none")
    print("copied:", ", ".join(os.path.basename(p) for p in copied) or "none")
    if MISSING:
        print("placeholders:", "；".join(MISSING))


if __name__ == "__main__":
    main()
