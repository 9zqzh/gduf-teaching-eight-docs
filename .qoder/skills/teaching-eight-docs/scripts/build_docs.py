def derive_lesson(course):
    chapters = course.get("chapters") or []
    lesson_chapters = []
    session_no = 1
    for idx, ch in enumerate(chapters, start=1):
        hours = chapter_hours(ch)
        sessions_count = max(1, (hours + 1) // 2)
        end = session_no + sessions_count - 1
        rng = f"第{session_no}次课" if end == session_no else f"第{session_no}-{end}次课"
        content_items = lst(ch.get("content"))
        lesson_chapters.append(
            {
                "no": ch.get("no") or f"第{idx}章",
                "title": ch.get("title", ""),
                "hours": hours,
                "goals": lst(ch.get("goals")),
                "key_points": txt(ch.get("key_points"), "本章教学重点"),
                "difficulties": txt(ch.get("difficulties"), "本章教学难点"),
                "methods": txt(ch.get("methods"), "本章教学方式"),
                "sessions": [
                    {
                        "range": rng,
                        "hours": hours,
                        "key_points": txt(ch.get("key_points"), "本次课教学重点"),
                        "difficulties": txt(ch.get("difficulties"), "本次课教学难点"),
                        "content": [{"heading": "教学内容要点", "items": content_items}] if content_items else [],
                        "organization": txt(ch.get("organization"), "教学组织"),
                        "homework": txt(ch.get("homework"), "作业布置"),
                        "references": "同课程简介参考教材",
                        "ideology": txt(ch.get("ideology"), "课程思政设计"),
                        "practice": txt(ch.get("practice", "无（理论课）")),
                        "reflection": lst(ch.get("reflection")) or [mark_missing("课后自我总结分析")],
                    }
                ],
            }
        )
        session_no = end + 1
    return lesson_chapters


