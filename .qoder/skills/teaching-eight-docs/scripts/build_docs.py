    add_title(doc, f"《{name}》课程教学大纲", size=22, space_before=0, space_after=12)

    # 一、课程信息
    add_section_heading(doc, "一、课程信息", space_before=0)
    nature = short_nature(course)
    nature_cell = f"必修（{'√' if nature == '必修' else ' '}）    选修（{'√' if nature == '选修' else ' '}）"
    ctype = str(course.get("type", "") or "")
