_ALIGN = {
    "left": WD_ALIGN_PARAGRAPH.LEFT,
    "center": WD_ALIGN_PARAGRAPH.CENTER,
    "right": WD_ALIGN_PARAGRAPH.RIGHT,
    "justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
}


def _style_cell(cell, size=10.5, bold=False, align="left", line=None, before=0, after=0, first=0, cn="宋体", en="宋体"):
    cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
    for p in cell.paragraphs:
        p.alignment = _ALIGN[align]
        pf = p.paragraph_format
        pf.space_before = Pt(before)
        pf.space_after = Pt(after)
        if line is None:
            pf.line_spacing = None
        elif line <= 3:
            pf.line_spacing = line
        else:
            pf.line_spacing = Pt(line)
        pf.first_line_indent = Pt(first)
        for run in p.runs:
            kit.set_run_font(run, size=size, bold=bold, cn=cn, en=en)


def _set_table_left(table):
    table.alignment = WD_TABLE_ALIGNMENT.LEFT


def _set_row_heights(table, heights_cm):
    for row, height in zip(table.rows, heights_cm):
        row.height = Cm(height)
        row.height_rule = WD_ROW_HEIGHT_RULE.AT_LEAST


def _set_template_grid(section, line_pitch=312):
    sect_pr = section._sectPr
    grid = sect_pr.find(qn("w:docGrid"))
    if grid is None:
        grid = OxmlElement("w:docGrid")
        sect_pr.append(grid)
    grid.set(qn("w:type"), "lines")
    grid.set(qn("w:linePitch"), str(line_pitch))


def mark_missing(label):
    if label not in MISSING:
        MISSING.append(label)
    return "（待补充）"


def g(data, *keys, default=""):
    cur = data
    for key in keys:
        if isinstance(cur, dict) and key in cur:
            cur = cur[key]
        else:
            return default
    return cur if cur is not None else default


def txt(value, label=None):
    if isinstance(value, list):
        value = "\n".join(str(v) for v in value if str(v).strip())
    value = clean_text(value)
    if not value and label:
        return mark_missing(label)
    return value


def field(obj, key, label):
    value = obj.get(key)
    return value if str(value or "").strip() else mark_missing(label)


def lst(value):
    if value is None:
        return []
    if isinstance(value, str):
        return [x.strip() for x in value.replace("\r", "").split("\n") if x.strip()]
    return [str(x).strip() for x in value if str(x).strip()]


def numbered(items):
    out = []
    for i, item in enumerate(items, start=1):
        item = str(item).strip()
        if item.startswith("[") and "]" in item[:5]:
            out.append(item)
        else:
            out.append(f"[{i}] {item}")
    return out


def short_nature(course):
    nature = str(course.get("nature", ""))
    if "选修" in nature:
        return "选修"
    if "必修" in nature:
        return "必修"
    return nature or "（待补充）"


