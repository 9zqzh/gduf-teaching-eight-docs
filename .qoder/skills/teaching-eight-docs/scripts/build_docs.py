def build_doc1(course, meta, out_dir):
    doc = new_document()
    section = doc.sections[0]
    section.left_margin = Cm(3.175)
    section.right_margin = Cm(3.175)
    section.top_margin = Cm(2.54)
    section.bottom_margin = Cm(2.54)
    _set_template_grid(section)

    add_p(
        doc,
        "课程简介",
        size=18,
        bold=True,
        align="center",
        cn="宋体",
        en="宋体",
        line_spacing=1.5,
        space_before=0,
        space_after=0,
    )
    add_p(doc, "", line_spacing=1.5)

    textbook = g(course, "textbook", default={}) or {}
    content = txt(course.get("summary") or g(course, "intro", "content"), "主要内容")
    parts = [part.strip() for part in re.split(r"[；;]", content) if part.strip()]
    if len(parts) > 1:
        content = "\n".join(part + "；" for part in parts[:-1]) + "\n" + parts[-1]

    refs = lst(textbook.get("references"))
    ref_text = "\n".join(f"{i}. {ref}" for i, ref in enumerate(refs, 1)) if refs else mark_missing("参考书")

    assessment = default_assessment(course)
    regular_names = [str(item.get("name", "")) for item in assessment["items"] if item.get("group") != "final"]
    final_names = [str(item.get("name", "")) for item in assessment["items"] if item.get("group") == "final"]
    if regular_names or final_names:
        assess_text = "\n".join(
            [
                f"期末：{'、'.join(final_names)}（共占{assessment['exam_ratio']}%）",
                f"平时：{'＋'.join(regular_names)}（共占{assessment['regular_ratio']}%）",
            ]
        )
    else:
        assess_text = txt(course.get("assessment_text"), "考核方式")

    rows = [
        ["课程名称", txt(course.get("name"), "课程名称")],
        ["课程代码", txt(course.get("code"), "课程代码")],
        ["课程性质", txt(course.get("nature"), "课程性质")],
        ["开设目的", txt(course.get("purpose") or g(course, "intro", "purpose"), "开设目的")],
        ["修读条件", txt(course.get("prerequisites"), "修读条件")],
        ["主要内容", content],
        ["教材", txt(textbook.get("main"), "教材")],
        ["参考书", ref_text],
        ["考核方式", assess_text],
    ]
    table_rows = []
    for label, value in rows:
        table_rows.append(
            [
                {"text": label, "bold": True, "align": "left", "cn": "宋体", "en": "宋体"},
                {"text": str(value), "align": "left", "cn": "宋体", "en": "宋体"},
            ]
        )
    table = add_table(doc, table_rows, [2.94, 12.70], size=10.5)
    _set_table_left(table)
    _set_row_heights(table, [0.965, 0.917, 0.965, 2.927, 0.944, 0.917, 0.917, 1.009, 1.009])

    styles = {
        0: (1.4, 0),
        1: (1.4, 0),
        2: (1.4, 0),
        3: (1.0, 0),
        4: (1.4, 0),
        5: (18, 21),
        6: (1.4, 0),
        7: (18, 22.9),
        8: (18, 0),
    }
    for idx, row in enumerate(table.rows):
        line, first = styles[idx]
        _style_cell(row.cells[0], bold=True, align="left", line=line)
        _style_cell(row.cells[1], bold=False, align="left", line=line, first=first)

    path = os.path.join(out_dir, "1、课程简介.docx")
    doc.save(path)
    return path


